package model;

/**
 * Mirror of `sale_item_batch_allocations` — batch-level traceability for one
 * sale item. One row per (sale_item, batch) pair produced by FEFO allocation.
 */
public class SaleItemBatchAllocation {

    private Long allocationId;
    private Long saleItemId;
    private Long batchId;
    private Integer quantity;

    /* Display-only fields from JOINs — not columns of the table. */
    private String batchNumber;
    private String productName;
    private java.sql.Date expiryDate;

    public Long getAllocationId() {
        return allocationId;
    }

    public void setAllocationId(Long allocationId) {
        this.allocationId = allocationId;
    }

    public Long getSaleItemId() {
        return saleItemId;
    }

    public void setSaleItemId(Long saleItemId) {
        this.saleItemId = saleItemId;
    }

    public Long getBatchId() {
        return batchId;
    }

    public void setBatchId(Long batchId) {
        this.batchId = batchId;
    }

    public Integer getQuantity() {
        return quantity;
    }

    public void setQuantity(Integer quantity) {
        this.quantity = quantity;
    }

    public String getBatchNumber() {
        return batchNumber;
    }

    public void setBatchNumber(String batchNumber) {
        this.batchNumber = batchNumber;
    }

    public String getProductName() {
        return productName;
    }

    public void setProductName(String productName) {
        this.productName = productName;
    }

    public java.sql.Date getExpiryDate() {
        return expiryDate;
    }

    public void setExpiryDate(java.sql.Date expiryDate) {
        this.expiryDate = expiryDate;
    }
}
